#!/usr/bin/env node

/**
 * Build script: vendor adapter dependency source files.
 *
 * Copies dependency source files and LICENSE files to vendor directories.
 * Adds export keywords to needed symbols so adapter wrappers can re-export.
 *
 * Usage: node scripts/build-adapters.mjs
 */

import { cpSync, existsSync, mkdirSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.cwd();
const NM = join(ROOT, "node_modules");

// Symbols to export from tree-sitter vendor/index.ts
const TREE_SITTER_EXPORTS = [
  "const MAX_ERRORS",
  "const CLOSER_LABELS",
  "function lineAt",
  "function formatError",
  "function collectErrors",
];

const ADAPTERS = [
  {
    name: "tree-sitter",
    pkg: "pi-tree-sitter",
    // Copy only needed files
    copyFiles: [
      "index.ts",
      "src/delimiter.ts",
      "src/grammar.ts",
      "LICENSE",
    ],
    // Add export keywords to needed symbols
    patchExports: TREE_SITTER_EXPORTS,
  },
];

function vendorAdapter(config) {
  const pkgDir = join(NM, config.pkg);
  const vendorDir = join(ROOT, "src/adapters", config.name, "vendor");

  if (!existsSync(pkgDir)) {
    console.error(`Package not found: ${config.pkg}`);
    process.exit(1);
  }

  // Clean vendor directory before copying
  if (existsSync(vendorDir)) {
    rmSync(vendorDir, { recursive: true, force: true });
    console.log(`  cleaned vendor/`);
  }

  mkdirSync(vendorDir, { recursive: true });

  // Copy files
  for (const file of config.copyFiles ?? []) {
    const src = join(pkgDir, file);
    const dst = join(vendorDir, file);
    if (existsSync(src)) {
      cpSync(src, dst);
      console.log(`  ${config.pkg}/${file} → vendor/${file}`);
    }
  }

  // Copy directories
  for (const dir of config.copyDirs ?? []) {
    const src = join(pkgDir, dir);
    const dst = join(vendorDir, dir);
    if (existsSync(src)) {
      cpSync(src, dst, { recursive: true });
      console.log(`  ${config.pkg}/${dir}/ → vendor/${dir}/`);
    }
  }

  // Patch vendor/index.ts if needed
  if (config.patchExports) {
    const vendorIndex = join(vendorDir, "index.ts");
    if (existsSync(vendorIndex)) {
      let content = readFileSync(vendorIndex, "utf-8");
      
      // Remove unused imports (handles single and multi-line)
      content = content.replace(/^import \{[\s\S]*?\} from "\.\/src\/edit-guard\.js";\n/gm, "");
      content = content.replace(/^import [\s\S]*?from "\.\/src\/languages\.js";\n/gm, "");
      content = content.replace(/^import [\s\S]*?from "\.\/src\/files\.js";\n/gm, "");
      content = content.replace(/^import \{ Text \} from "@earendil-works\/pi-tui";\n/gm, "");
      
      // Add export keywords to needed symbols
      for (const symbol of config.patchExports) {
        const regex = new RegExp(`^(${symbol.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")})`, "gm");
        content = content.replace(regex, "export $1");
      }
      writeFileSync(vendorIndex, content);
      console.log(`  patched vendor/index.ts`);
    }

    // Generate declaration file for vendor exports
    if (config.name === "tree-sitter") {
      const dtsContent = `/**
 * Type declarations for vendored pi-tree-sitter exports.
 * Generated by build-adapters.mjs — do not edit manually.
 */
import type { Tree, Node as TSNode } from "web-tree-sitter";

export declare const MAX_ERRORS: number;
export declare const CLOSER_LABELS: Record<string, string>;
export declare function lineAt(source: string, offset: number): string;
export declare function formatError(node: TSNode, source: string): string;
export declare function collectErrors(tree: Tree, source: string): string[];
`;
      writeFileSync(join(vendorDir, "index.d.ts"), dtsContent);
      console.log(`  generated vendor/index.d.ts`);

      // Generate standalone adapter module that re-exports from vendor
      const adapterDir = join(ROOT, "src/adapters", config.name);
      const adapterContent = `/**
 * Tree-sitter adapter exports — re-exports from vendored pi-tree-sitter.
 *
 * Generated by build-adapters.mjs — do not edit manually.
 * Vendor files are excluded from typecheck; this module provides
 * the clean import point for the adapter.
 */

// Re-export from vendored pi-tree-sitter
export {
  lineAt,
  formatError,
  collectErrors,
  MAX_ERRORS,
  CLOSER_LABELS,
} from "./vendor/index.js";
`;
      writeFileSync(join(adapterDir, "exports.js"), adapterContent);
      writeFileSync(join(adapterDir, "exports.d.ts"), dtsContent);
      console.log(`  generated tree-sitter/exports.js and exports.d.ts`);
    }
  }
}

console.log("Vendoring adapters...");

for (const config of ADAPTERS) {
  console.log(`\n${config.name}:`);
  vendorAdapter(config);
}

console.log("\nDone.");
